# 60-dotfiles.sh
# ---------------------------------------------------------------------
# =====================================================================
#  Dotfiles: sway, C bar (native Wayland), foot, wofi, mako, swaylock
# ---------------------------------------------------------------------
#  Every file is written through install_user_file(), which backs up a
#  previous file and records it in the manifest for --uninstall.
# =====================================================================

install_user_file() {
	# install_user_file <abs-path> <mode>  (content on stdin)
	local path="$1" mode="${2:-644}"
	local tmp; tmp="$(mktemp)"
	cat >"${tmp}"          # read stdin exactly once
	if [[ -e "${path}" ]] && cmp -s "${tmp}" "${path}"; then
		rm -f "${tmp}"
		ui_dim "unchanged: ${path}"
		return 0
	fi
	mkdir -p "$(dirname "${path}")"
	if [[ -e "${path}" || -L "${path}" ]]; then
		backup_path "${path}"
	fi
	install -m "${mode}" "${tmp}" "${path}"
	rm -f "${tmp}"
	register_file "${path}"
	ui_ok "wrote ${path}"
}

