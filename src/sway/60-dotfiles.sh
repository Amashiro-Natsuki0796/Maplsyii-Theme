dotfiles_install() {
	ui_hdr "Dotfiles"
	write_sway
	write_bar
	write_foot
	# alacritty is no longer the default terminal, but its config is still
	# written when the binary is present so switching back is a one-liner.
	if have alacritty; then write_alacritty; fi
	write_wofi
	write_mako
	write_swaylock
	write_btop
	user_dirs_create
	# PCManFM is part of the optional apps component; configure it only when
	# the file manager is present.
	if command -v pcmanfm >/dev/null 2>&1; then
		write_pcmanfm
	fi
	chown_user "${HOME_DIR}/.config"
	ui_ok "dotfiles written to ${HOME_DIR}/.config"
}

