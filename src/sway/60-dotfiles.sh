	register_file "${dir}/pcmanfm.conf"

	# Sidebar bookmarks: ~/.config/gtk-3.0/bookmarks, one entry per line as
	# "URI [Label]".
	#
	# PCManFM renders its own places first (Home Folder, Desktop, Trash Can),
	# driven by GIO's volume monitor, so listing those here would duplicate
	# them. Computer and Network are not offered automatically on a machine
	# with no mounted volumes and no gvfs network backends, which is why they
	# are added explicitly:
	#   computer:///  resolves to the "computer" icon; file:/// would only
	#                 get a plain folder icon.
	#   network:///   PCManFM's own network browser, no gvfs required.
	local bm="${HOME_DIR}/.config/gtk-3.0/bookmarks"
	mkdir -p "$(dirname "${bm}")"
	{
		printf 'computer:/// Computer\n'
		printf 'network:/// Network\n'
	} >"${bm}"
	register_file "${bm}"
	chown_user "${bm}"
	return 0
}


write_foot() {
	local dir="${HOME_DIR}/.config/foot"
	# foot reads the background alpha from the colour itself, so transparency
	# needs no compositor effect. Option placement matters: every key has one
	# valid section, and a misplaced one makes foot print a config error on
	# every start (alpha belongs under [colors], lines under [scrollback]).
	install_user_file "${dir}/foot.ini" 644 <<'FOOT'
# foot - Everforest (dark)

[main]
font=JetBrains Mono:size=11
dpi-aware=no
# 2px of breathing room so the text does not touch the sway border.
pad=2x2
selection-target=both

[scrollback]
# Same wheel distance as the i3 terminal: the st build maps Button4/5 to
# kscrollup/kscrolldown with an argument of 1, i.e. one line per notch. foot
# defaults to 3.0, which scrolls three times as fast and makes the two
# terminals feel different under the same hand.
lines=10000
multiplier=1.0

[cursor]
style=block
blink=yes

[mouse]
hide-when-typing=yes

# URLs: under Control, and openable with Control+left-click.
#
# st underlines every URL while Ctrl is held and opens the one under the
# pointer on Ctrl+click. foot has no "open the URL at this coordinate" action -
# its URL handling is mode based, and mouse bindings receive no cursor
# position - so the interaction is the closest equivalent it can express:
#
#   * osc8-underline=always   every URL is underlined all the time, which is
#                             the visible half of st's Ctrl behaviour (foot
#                             cannot make the underline follow a modifier).
#   * Control+BTN_LEFT        starts URL mode instead of opening a link
#                             directly; every visible URL gets a jump label,
#                             and one keystroke opens it. One extra keystroke
#                             compared with st, but the same "Ctrl + click on a
#                             link" starting gesture.

[url]
# URLs are always underlined, so a link is visible without entering URL mode
# first. Opening one is foot's own URL mode (Control+Shift+o by default): every
# visible link gets a jump label and one keystroke opens it.
#
# st opens the link directly on Ctrl+click. foot cannot: its URL handling is
# mode based and its mouse bindings receive no cursor position, so there is no
# "open the URL at this coordinate" action to bind to. The defaults are left
# untouched here rather than clearing select-begin-block to steal
# Control+BTN_LEFT for URL mode - entering a mode on click is not the same
# interaction, and it would cost the block-selection shortcut.
osc8-underline=always
launch=xdg-open ${url}

[csd]
# The compositor draws the frame; foot's own title bar is not wanted.
preferred=server

[colors]
# Matches the i3 rice's terminal exactly: st is built with ST_ALPHA=78, and
# foot's `alpha` is the same quantity (opacity, 1.0 = solid), so both
# terminals let the same amount of wallpaper through.
alpha=0.78
background=000000
foreground=d3c6aa
regular0=000000
regular1=e67e80
regular2=a7c080
regular3=dbbc7f
regular4=7fbbb3
regular5=d699b6
regular6=83c092
regular7=d3c6aa
bright0=7a8478
bright1=e67e80
bright2=a7c080
bright3=dbbc7f
bright4=7fbbb3
bright5=d699b6
bright6=83c092
bright7=fffbef

[key-bindings]
clipboard-copy=Control+Shift+c
clipboard-paste=Control+Shift+v
primary-paste=Shift+Insert
spawn-terminal=Control+Shift+n
FOOT
}



