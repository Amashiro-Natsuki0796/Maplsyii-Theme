### Autostart
exec_always --no-startup-id dbus-update-activation-environment --systemd WAYLAND_DISPLAY SWAYSOCK XDG_CURRENT_DESKTOP=sway
exec --no-startup-id lxpolkit
exec --no-startup-id mako
# Mirror notification bodies into a log, so the history menu can show what a
# notification said. mako keeps only summary/app/urgency; the body is carried
# by the D-Bus Notify call, which this observes without taking the name away
# from mako.
exec --no-startup-id /usr/local/bin/sway-everforest-notify-log
# Input method: start fcitx5 with the session, like the i3 config does.
#
# sway does not process XDG autostart entries - that is a desktop-environment
# feature - so the org.fcitx.Fcitx5.desktop file in ~/.config/autostart is
# never run here. Starting it explicitly is what makes the IME available after
# login instead of only after opening a terminal and launching it by hand.
#
# The --disable list differs from the i3 config on purpose: i3 turns off
# wayland,waylandim because X11 cannot use them; here they are the two
# frontends that matter, so the list drops them and keeps the rest off.
exec --no-startup-id sh -c 'command -v fcitx5 >/dev/null 2>&1 && ! pgrep -x fcitx5 >/dev/null 2>&1 && exec fcitx5 -d --disable virtualkeyboard,emoji,table,spell,kimpanel,quickphrase,unicode,clipboard,notificationitem,fcitx4frontend,ibusfrontend'
# Ctrl+Space toggles the input method.
#
# Under Wayland a client cannot grab the keyboard globally: fcitx5's own
# TriggerKeys setting only works on X11, so relying on it here left the key
# dead. The compositor is the only process that sees every keystroke, so the
# binding lives in sway and calls fcitx5-remote directly.
#
# fcitx5's in-app hotkey is switched off in its config so the two cannot fight
# over the same combination - see write_fcitx_env().
bindsym Control+space exec --no-startup-id fcitx5-remote -t
exec --no-startup-id swaybg -i "$wall" -m fill
# The bar: the native Wayland C bar, and nothing else.
#
# No waybar fallback on purpose. A bar is not optional - without one there is
# no workspace indicator, no clock and no way to see whether the session is
# healthy - so a silent switch to a different bar would hide a broken build
# behind a UI that looks almost right. If the C bar is missing, spawn() prints
# the failure into the sway log and the desktop shows an obvious empty strip,
# which is the honest signal that something needs fixing here.
exec --no-startup-id /usr/local/bin/i3-everforest-bar-wl

# ---- frosted glass ------------------------------------------------------
#
# swayfx (the blur fork of sway) renders the blur itself rather than letting a
# separate compositor do it, which is what makes this possible on Wayland: a
# client cannot read the pixels behind it, so a launcher could never blur its own
# backdrop the way rofi does under picom.
#
# blur_xray blurs *everything below* a window, not just what the window
# itself draws - that is what turns a translucent popup into frosted glass.
# Without it only the popup's own pixels would be blurred, which is invisible.
blur on

# blur_xray, per surface type.
#
# For windows it must stay ON: the global value feeds
#   should_optimize_blur = config->blur_xray || !could_container_overlap(con)
# and a fullscreen, non-floating window gives could_container_overlap() == false,
# so with xray off such a window is *forced* into the bottom-layer-only path and
# ends up blurring the wallpaper.
#
# Layer surfaces are handled separately below: they each get blur_xray disabled
# through layer_effects, so wofi frosts the real backdrop rather than the
# wallpaper.
blur_xray on
blur_radius 6
blur_passes 3
blur_brightness 0.9
blur_contrast 0.9
blur_saturation 1.0
blur_noise 0.02

# wofi is a layer-shell surface, not a window, so for_window does not apply:
# it lives in the overlay layer and never enters the window tree. swayfx gives
# layer surfaces their own command, and it matches on the surface namespace -
# the string a client passes to get_layer_surface ("wofi", "i3-everforest-bar").
layer_effects wofi blur enable, blur_xray disable

# The bar and its tooltip get NO blur.
#
# The bar is already opaque (panel_alpha 1.00 by default), so blurring behind it
# could not show through the panel - it only affected the transparent margin
# around the rounded corners, where it turned the wallpaper into a bright washed
# strip. Measured: the same pixel reads (28,27,34) with no bar and (49,0,0) with
# it, a visible glow that is not in the wallpaper.
#
# layer_effects i3-everforest-bar is therefore deliberately absent. The tooltip
# paints its own translucent panel and is left alone for the same reason the
# wofi rule exists only for wofi.

# Ordinary windows: the file manager and the settings dialogs. These are
# translucent enough that blur reads; everything else stays opaque and costs
# nothing.
# The power menu must cover the whole output. GtkWindow.fullscreen() is a no-op
# under wlroots, so the window was tiled next to the current one and its scrim
# only covered half the screen.
# Floating and sized to the output, NOT `fullscreen enable`.
#
# A fullscreen container loses its alpha compositing in scenefx: the window
# still reports an ARGB buffer, but what reaches the screen is the scrim
# blended against black, so the menu showed a flat dark rectangle with no
# frost. Floating at output size keeps the alpha path intact - the same pixels
# then blend against the windows behind them, which is what the blur picks up.
for_window [app_id="sway-everforest-powermenu-ui"] floating enable, border none, blur on
for_window [app_id="fcitx5-config-qt"] blur on
for_window [app_id="nm-connection-editor"] blur on
for_window [class="nm-connection-editor"] blur on
# No idle handling: the session does not lock itself, blank the screen or
# suspend. Off at the user's request - a terminal-only desktop that gets locked
# out of nowhere is worse than one that stays on.
#
# swayidle is deliberately not started. Manual locking still works:
#   Mod+Escape runs swaylock.
# To restore the old behaviour, add back:
#   exec --no-startup-id swayidle -w \
#       timeout 600 'swaylock -f -c 1e2326' \
#       timeout 900 'swaymsg "output * power off"' \
#       resume 'swaymsg "output * power on"' \
#       before-sleep 'swaylock -f -c 1e2326'

### XWayland
#
# Disabled deliberately. Every program this rice starts is a native Wayland
# client - foot, wofi, pcmanfm, grim/slurp/swappy, mako, swaylock, swaybg, the
# C bar, and Firefox via MOZ_ENABLE_WAYLAND=1 - so nothing ever connects to
# Xwayland, and it only costs memory: measured at 46 MB PSS, roughly a quarter
# of the whole session's baseline.
#
# The trade-off is that a stray X11 program will fail with "cannot open
# display". If that ever happens, delete this line (or set it to `enable`) and
# restart the session; nothing else depends on it.
xwayland disable
SWAYCONF
	install_user_file "${cfg}" 644 <"${tmp}"
	rm -f "${tmp}"
}

write_bar() {
	# Bar configuration.
	#
	# The bar is the native Wayland C program (assets/bar-wl), not waybar, so
	# there is no JSON or CSS to write here - the layout and colours live in
	# that program. What the installer still records is the user's transparency
	# choice, which the bar reads at startup.
	local dir="${HOME_DIR}/.config/i3-everforest"
	local file="${dir}/bar.conf"

	if [[ ${OPT_DRY_RUN} -eq 1 ]]; then
		ui_dim "would write ${file} (bar opacity: ${BAR_OPACITY:-solid})"
		return 0
	fi

	mkdir -p "${dir}"
	{
		printf '# Bar preferences, read by /usr/local/bin/i3-everforest-bar-wl\n'
		printf '# opacity: solid | soft | clear\n'
		printf 'opacity=%s\n' "${BAR_OPACITY:-solid}"
	} >"${file}"
	register_file "${file}"
	chown_user "${file}" 2>/dev/null || true
	ui_ok "bar opacity: ${BAR_OPACITY:-solid}"
	return 0
}

user_dirs_create() {
	# xdg-user-dirs creates Desktop/Documents/Downloads/Music/Pictures/Videos
	# from the localized names in /etc/xdg/user-dirs.defaults. Without this the
	# bookmarks and the file manager sidebar point at directories that do not
	# exist yet.
	if command -v xdg-user-dirs-update >/dev/null 2>&1; then
		if [[ ${OPT_DRY_RUN} -eq 1 ]]; then
			ui_dim "would create the XDG user directories"
			return 0
		fi
		as_user xdg-user-dirs-update --force >/dev/null 2>&1 ||
			as_user xdg-user-dirs-update >/dev/null 2>&1 || true
	fi
	# Make sure the set we link to exists even when xdg-user-dirs is absent.
	local d
	for d in Desktop Documents Downloads Music Pictures Videos Public Templates; do
		[[ -d "${HOME_DIR}/${d}" ]] || mkdir -p "${HOME_DIR}/${d}" 2>/dev/null || true
		chown_user "${HOME_DIR}/${d}" 2>/dev/null || true
	done
	ui_ok "user directories ready"
	return 0
}

