write_st() {
	# st (suckless terminal) replaces kitty: the same Everforest palette, but
	# ~8 MB resident instead of ~130 MB. It is not packaged for Debian, so the
	# installer builds it once and installs the binary; the patched config.h
	# carries the colours so the look matches the rest of the rice.
	local src="/usr/local/src/i3-everforest-st"
	local bin="/usr/local/bin/st"

	if [[ ${OPT_DRY_RUN} -eq 1 ]]; then
		ui_dim "would build ${bin} from source"
		return 0
	fi

	# Rebuild when the installed binary predates the config the installer
	# writes. Skipping on "already installed" alone meant a config change
	# (a different chscale, say) never reached the binary on an existing
	# machine - the installer reported success while the old build stayed in
	# place.
	if command -v st >/dev/null 2>&1 && \
		"${bin}" -v 2>&1 | grep -q '^st-'; then
		local stamp="${src}/.built-config"
		if [[ -f "${stamp}" ]] && [[ "${stamp}" -nt "${bin}" ]]; then
			ui_dim "st already installed"
			return 0
		fi
		ui_step "rebuilding st (config changed)"
	fi

	if ! command -v make >/dev/null 2>&1 || ! command -v cc >/dev/null 2>&1; then
		ui_warn "no C toolchain - st cannot be built"
		return 0
	fi

	mkdir -p "${src}" 2>/dev/null
	chmod 755 "${src}" 2>/dev/null

	local tarball="${src}/st.tar.gz"
	if [[ ! -s "${src}/st/config.h" ]]; then
		curl -fsSL https://dl.suckless.org/st/st-0.9.2.tar.gz \
			-o "${tarball}" 2>/dev/null || {
			ui_warn "could not download st"
			return 0
		}
		tar xzf "${tarball}" -C "${src}" --strip-components=1 2>/dev/null
	fi

	# Give st a real default window title: with opt_title == NULL the window
	# name is empty and the bar shows the class ("st") instead.
	python3 - "${src}/x.c" <<'PYTITLE'
import sys

path = sys.argv[1]
text = open(path, encoding="utf-8").read()
if "opt_title = \"Simple Terminal\"" not in text:
    text = text.replace('static char *opt_title = NULL;',
                        'static char *opt_title = "Simple Terminal";')
open(path, "w", encoding="utf-8").write(text)
PYTITLE

	# Start from the shipped config.def.h and patch only the values we change:
	# replacing the file wholesale dropped required declarations (cols, rows,
	# selmasks, ...) and broke the build.
	cp "${src}/config.def.h" "${src}/config.h"

	# Palette: the rice's Everforest colours.
	python3 - "${src}/config.h" <<'PYPATCH'
import re
import sys

path = sys.argv[1]
text = open(path, encoding="utf-8").read()

palette = """static const char *colorname[] = {
	/* Exactly the values from the rice's kitty.conf. */
	[0]   = "#000000", [1]   = "#e67e80", [2]   = "#a7c080", [3]   = "#dbbc7f",
	[4]   = "#7fbbb3", [5]   = "#d699b6", [6]   = "#83c092", [7]   = "#d3c6aa",
	[8]   = "#7a8478", [9]   = "#e67e80", [10]  = "#a7c080", [11]  = "#dbbc7f",
	[12]  = "#7fbbb3", [13]  = "#d699b6", [14]  = "#83c092", [15]  = "#fffbef",
	[255] = 0,
	[256] = "#d3c6aa",  /* foreground */
	[257] = "#000000",  /* background */
	[258] = "#d3c6aa",  /* cursor */
	[259] = "#1e2326",  /* reverse cursor */
};
"""

text = re.sub(r"static const char \*colorname\[\] = \{.*?\n\};",
              palette.rstrip(), text, flags=re.S)

# Larger text and a comfortable inset from the window edge.
text = re.sub(r'^static char \*font\s*=.*$',
              'static char *font = '
              '"JetBrains Mono:pixelsize=14:antialias=true:hinting=true:hintstyle=hintslight:autohint=false:rgba=rgb";',
              text, flags=re.M)
text = re.sub(r'^static int borderpx\s*=.*$', 'static int borderpx = 2;',
              text, flags=re.M)

# kitty blinks the block cursor every 0.5s; st uses milliseconds.
text = re.sub(r'^static unsigned int blinktimeout\s*=.*$',
              'static unsigned int blinktimeout = 500;', text, flags=re.M)

# Point the default colours at the palette slots filled above. config.def.h
# leaves defaultbg at 259 (a lighter shade), which made the whole window look
# washed-out grey instead of black.
text = re.sub(r'^unsigned int defaultfg\s*=.*$', 'unsigned int defaultfg = 256;',
              text, flags=re.M)
text = re.sub(r'^unsigned int defaultbg\s*=.*$', 'unsigned int defaultbg = 257;',
              text, flags=re.M)
text = re.sub(r'^unsigned int defaultcs\s*=.*$', 'unsigned int defaultcs = 258;',
              text, flags=re.M)
text = re.sub(r'^static unsigned int defaultrcs\s*=.*$',
              'static unsigned int defaultrcs = 259;', text, flags=re.M)

# Line-height scale.
#
# A terminal cell is much taller than it is wide (about 8.4 x 19.6 px for
# JetBrains Mono at pixelsize 14), so ASCII art built from square characters -
# the Debian swirl in `mf` - is drawn about a third too tall. chscale shrinks
# the line box, which brings that art back to roughly square and tightens the
# line spacing at the same time. 0.85 is the point where the swirl measures
# close to 1:1 without the text looking cramped.
text = re.sub(r'^static float chscale\s*=.*$',
              'static float chscale = 0.85;', text, flags=re.M)

open(path, "w", encoding="utf-8").write(text)
PYPATCH

	# Background-only transparency, the way kitty's background_opacity works.
	#
	# st picks the default (24-bit) visual, which has no alpha channel, so a
	# translucent background colour is simply ignored. Give it an ARGB visual
	# and paint the background with XRender using ST_ALPHA, leaving the glyphs
	# fully opaque - picom cannot do this because it dims the whole window.
	python3 - "${src}/x.c" <<'PYPATCH2'
import re
import sys

path = sys.argv[1]
text = open(path, encoding="utf-8").read()

if "xw.depth" not in text:
    # 1) Prefer a 32-bit TrueColor visual when one exists.
    text = text.replace(
        "\txw.vis = XDefaultVisual(xw.dpy, xw.scr);",
        "\t/* Prefer an ARGB visual so a translucent background is possible. */\n"
        "\t{\n"
        "\t\tXVisualInfo vi;\n"
        "\t\tif (XMatchVisualInfo(xw.dpy, xw.scr, 32, TrueColor, &vi)) {\n"
        "\t\t\txw.vis = vi.visual;\n"
        "\t\t\txw.depth = 32;\n"
        "\t\t} else {\n"
        "\t\t\txw.vis = XDefaultVisual(xw.dpy, xw.scr);\n"
        "\t\t\txw.depth = XDefaultDepth(xw.dpy, xw.scr);\n"
        "\t\t}\n"
        "\t}")

    # 2) A 32-bit visual needs its own colormap, not the root's.
    text = text.replace(
        "\txw.cmap = XDefaultColormap(xw.dpy, xw.scr);",
        "\txw.cmap = (xw.depth == 32)\n"
        "\t\t? XCreateColormap(xw.dpy, XRootWindow(xw.dpy, xw.scr),\n"
        "\t\t\txw.vis, AllocNone)\n"
        "\t\t: XDefaultColormap(xw.dpy, xw.scr);")

    # 3) The back buffer must match the window depth too.
    text = text.replace(
        "xw.buf = XCreatePixmap(xw.dpy, xw.win, win.w, win.h,\n\t\t\tDefaultDepth(xw.dpy, xw.scr));",
        "xw.buf = XCreatePixmap(xw.dpy, xw.win, win.w, win.h,\n\t\t\txw.depth);")

    # 4) The GC must be bound to the window, not the root: drawing into a 32-bit
    # pixmap with a 24-bit GC raises BadMatch.
    text = text.replace(
        "dc.gc = XCreateGC(xw.dpy, parent, GCGraphicsExposures,",
        "dc.gc = XCreateGC(xw.dpy, xw.win, GCGraphicsExposures,")

    # 5) A 32-bit window must not have an opaque background pixel.
    text = text.replace(
        "\txw.attrs.background_pixel = dc.col[defaultbg].pixel;",
        "\txw.attrs.background_pixel = (xw.depth == 32)\n"
        "\t\t? 0 : dc.col[defaultbg].pixel;")

    # 6) Apply the background alpha after the palette is loaded:
    # XftColorAllocName always returns alpha=0xffff.
    text = text.replace(
        "\tloaded = 1;\n}",
        "\tif (xw.depth == 32) {\n"
        "\t\tunsigned short a = (unsigned short)(65535.0 *\n"
        "\t\t\t((getenv(\"ST_ALPHA\") ? atoi(getenv(\"ST_ALPHA\")) : 78) / 100.0));\n"
        "\t\tdc.col[defaultbg].color.alpha = a;\n"
        "\t}\n"
        "\tloaded = 1;\n}", 1)

    # 6) Create the window with that depth and colormap.
    text = text.replace(
        "\t\t\twin.w, win.h, 0, XDefaultDepth(xw.dpy, xw.scr), InputOutput,\n"
        "\t\t\txw.vis, CWBackPixel | CWBorderPixel | CWBitGravity",
        "\t\t\twin.w, win.h, 0, xw.depth, InputOutput,\n"
        "\t\t\txw.vis, CWBackPixel | CWBorderPixel | CWBitGravity")

    # 3) Background alpha from ST_ALPHA so only the backdrop is see-through.
    text = text.replace(
        "colbg.alpha = 0xffff;",
        "colbg.alpha = (unsigned short)(65535.0 *\n"
        "\t\t\t((getenv(\"ST_ALPHA\") ? atoi(getenv(\"ST_ALPHA\")) : 78) / 100.0));")

open(path, "w", encoding="utf-8").write(text)
PYPATCH2

	# xw.depth is new; the XWindow struct lives in x.c.
	python3 - "${src}/x.c" <<'PYPATCH3'
import sys

path = sys.argv[1]
text = open(path, encoding="utf-8").read()
if "\tint depth;" not in text:
    text = text.replace("\tVisual *vis;", "\tVisual *vis;\n\tint depth;", 1)
open(path, "w", encoding="utf-8").write(text)
PYPATCH3

	# Font and padding, matching the rice.
	sed -i \
		-e 's|^static char \*font.*|static char *font = "JetBrains Mono:pixelsize=14:antialias=true:hinting=true:hintstyle=hintslight:autohint=false:rgba=rgb";|' \
		-e 's|^static int borderpx.*|static int borderpx = 2;|' \
		"${src}/config.h" 2>/dev/null

	( cd "${src}" && make clean >/dev/null 2>&1 && make >/dev/null 2>&1 ) || {
		ui_warn "st failed to build"
		return 0
	}

	install -m 755 "${src}/st" "${bin}" 2>/dev/null && \
		register_file "${bin}"
	if command -v setcap >/dev/null 2>&1; then
		setcap cap_net_ext_admin+ep "${bin}" 2>/dev/null || true
	fi
	# Record the config this binary was built from, so a later run can tell
	# whether it is stale (see the check at the top of this function).
	printf '%s\n' "$(date -Is)" >"${src}/.built-config" 2>/dev/null || true
	ui_ok "built ${bin}"
}


