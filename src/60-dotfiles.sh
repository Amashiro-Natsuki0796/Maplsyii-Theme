write_picom() {
	local dir="${HOME_DIR}/.config/picom"
	# The reference has no blur and no fancy effects: picom is here to give
	# X11 the per-window alpha the wallpaper shows through, plus a soft
	# shadow. The bar keeps its own translucency, so it is excluded.
	install_user_file "${dir}/picom.conf" 644 <<'PICOM'
# picom - Everforest
#
# Compositing (so ARGB windows such as the bar blend),
# a soft shadow, and a dual-kawase blur limited to the power menu - its
# translucent scrim then reads as frosted glass. Nothing else is blurred, so
# the rest of the rice looks exactly as before.

backend = "glx";

# Frosted glass for the full-screen power menu only.
blur-background = true;
blur-method = "dual_kawase";
blur-strength = 6;
blur-background-frame = false;
blur-background-fixed = false;
# The bar is always a plain transparent frame - never frosted - so it is
# excluded from blur outright.
blur-background-exclude = [
    "class_g = 'i3-frame'",
    "class_g = 'Dunst'",
    "class_g = 'i3-everforest-bar-c'",
    # slop is the region selector used by the screenshot button: as an ARGB
    # overlay it would otherwise frost the whole screen.
    "class_g = 'slop'",
    "class_g = 'i3-everforest-tooltip'",
    "window_type = 'desktop'",
    # Context menus are ARGB popups, so picom blurred everything behind them and
    # every right-click menu ended up wrapped in a frosted halo. They are small,
    # text-dense and open for a second - blur only makes them harder to read.
    "window_type = 'popup_menu'",
    "window_type = 'dropdown_menu'",
    "window_type = 'menu'",
    "window_type = 'combo'",
    "window_type = 'tooltip'",
    "window_type = 'notification'",
    "window_type = 'dnd'",
];

# Shadows: subtle, so the 1px Everforest border stays the visual edge.
shadow = true;
shadow-radius = 12;
shadow-opacity = 0.35;
shadow-offset-x = -8;
shadow-offset-y = -8;

# The bar is a translucent panel; a shadow under it would double its edge.
shadow-exclude = [
    "class_g = 'i3-everforest-bar-c'",
    "class_g = 'i3-everforest-tooltip'",
    "class_g = 'i3-frame'",
    "_NET_WM_WINDOW_TYPE@:a = 'DOCK'",
];

# Alacritty, the launcher and the notification daemon carry their own alpha
# (foot's 0.60 ported over); letting picom fade again would double-dim them.
opacity-rule = [
    "100:class_g = 'i3-everforest-bar-c'",
    "100:class_g = 'i3-everforest-tooltip'",
    "100:class_g = 'Rofi'",
    "100:class_g = 'Dunst'",
    /* st renders its own background alpha (ST_ALPHA), like kitty's
     * background_opacity - keep picom from dimming its text as well. */
    "100:class_g = 'st-256color'",
    "100:class_g = 'st'",
];

# Keep fullscreen video and games unredirected so they do not stutter.
unredir-if-possible = true;
unredir-if-possible-exclude = [
    "class_g = 'i3-everforest-bar-c'",
    "class_g = 'i3-everforest-tooltip'",
];

# i3 reparents every window; without this the shadow is drawn around the
