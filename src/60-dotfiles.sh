dotfiles_install() {
	ui_hdr "Dotfiles"
	write_i3
	write_bar
	write_bar_opacity
	write_border_ctl
	write_foot
	# st is the default terminal; it is built from source on install.
	write_st
	write_st_desktop
	write_rofi
	write_dunst
	write_picom
	write_i3lock
	write_btop
	# X11 sessions read ~/.xsessionrc and ~/.Xresources, not environment.d.
	write_xsession_env
	user_dirs_create
	# PCManFM is part of the optional apps component; configure it only when
	# the file manager is present.
	if command -v pcmanfm >/dev/null 2>&1; then
		write_pcmanfm
	fi
	chown_user "${HOME_DIR}/.config"
	ui_ok "dotfiles written to ${HOME_DIR}/.config"
}
