write_st_desktop() {
	# st ships no .desktop file, so it never appeared in rofi's drun list.
	local desk="/usr/local/share/applications/st.desktop"
	mkdir -p "$(dirname "${desk}")" 2>/dev/null
	cat >"${desk}" <<'STDESK'
[Desktop Entry]
Type=Application
Name=Simple Terminal
Comment=Simple terminal
GenericName=Terminal
Exec=st
Icon=utilities-terminal
Terminal=false
Categories=System;TerminalEmulator;
Keywords=shell;prompt;command;terminal;
StartupNotify=true
STDESK
	chmod 644 "${desk}"
	register_file "${desk}"
	# Some rofi builds only scan the system directory.
	if [[ -d /usr/share/applications ]]; then
		cp "${desk}" /usr/share/applications/st.desktop 2>/dev/null &&
			chmod 644 /usr/share/applications/st.desktop 2>/dev/null &&
			register_file /usr/share/applications/st.desktop
	fi
	ui_ok "st desktop entry installed"

	# The rice's icon theme carries only a few application icons, so entries
	# like the file manager showed a blank row. Drop a user-level copy of
	# index.theme whose inheritance falls back to Numix-Circle (12k icons).
	local ico_dir="${HOME_DIR}/.local/share/icons/${ICON_NAME}"
	local src_index="/usr/share/icons/${ICON_NAME}/index.theme"
	[[ -f "${src_index}" ]] || return 0
	mkdir -p "${ico_dir}" 2>/dev/null
