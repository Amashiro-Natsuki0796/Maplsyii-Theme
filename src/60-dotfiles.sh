	local bm="${HOME_DIR}/.config/gtk-3.0/bookmarks"
	mkdir -p "$(dirname "${bm}")"
	{
		printf 'computer:/// Computer\n'
		printf 'network:/// Network\n'
	} >"${bm}"
	register_file "${bm}"
	chown_user "${bm}"
	return 0
}


