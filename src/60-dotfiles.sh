### Autostart
# dbus-update-activation-environment keeps the session bus in sync with the
# X11 session, which GTK/portal/notifications rely on. XDG_CURRENT_DESKTOP
# must be i3: portal backends pick their implementation from it, and a wrong
# value makes them look for a desktop that is not running.
exec_always --no-startup-id dbus-update-activation-environment --systemd DISPLAY XAUTHORITY XDG_SESSION_TYPE XDG_CURRENT_DESKTOP=i3
exec --no-startup-id lxpolkit
# picom supplies the compositor: shadows only, no blur, and the bar is
# excluded so its own alpha is drawn untouched. The rules live in a config
# file because i3 does not honour shell quoting on an exec line, which used
# to strip the quotes off the shadow-exclude rule.
exec --no-startup-id picom --config "$HOME/.config/picom/picom.conf"
exec --no-startup-id dunst
# Input method. i3 has no xdg-autostart, so the ~/.config/autostart entry that
# sway uses is not enough here; start it directly, but only when fcitx5 exists
# and is not already running.
exec --no-startup-id sh -c 'command -v fcitx5 >/dev/null 2>&1 && ! pgrep -x fcitx5 >/dev/null 2>&1 && exec fcitx5 -d --disable virtualkeyboard,emoji,table,spell,kimpanel,quickphrase,unicode,clipboard,notificationitem,fcitx4frontend,ibusfrontend,wayland,waylandim'
exec --no-startup-id xwallpaper --zoom "$wall"
# The bar is a dock strip at an exact offset. i3 places tiled clients itself,
# so the bar is declared floating, borderless and pinned with a move command;
# the bar program also sets _NET_WM_WINDOW_TYPE_DOCK and its strut.
# The bar is a GTK dock: i3 reserves a dockarea exactly as tall as the dock
# window, so windows never overlap the strip. i3 has no "top offset" for a
# dock, which means the window must *include* the reference's 6px top margin -
# otherwise the workspace starts at y=34 and paints over the bar's bottom edge.
for_window [class="^i3-everforest-bar-c$"] floating enable, border none
for_window [class="^i3-everforest-bar-c$"] move position 0 px 0 px
for_window [class="^i3-everforest-bar-c$"] sticky enable
# exec_always, not exec: a plain `exec` runs once per i3 *start*, so
# `i3-msg restart` left the desktop with no bar at all. exec_always re-runs on
# every reload, which is what makes the bar come back after a reload.
#
# It re-runs unconditionally, so two details matter:
#   - guard with pgrep, or every reload would add another bar
#   - start it with `&`, not `exec`: `exec` replaces the shell that i3 waits
#     on, and i3 then treats the long-lived bar as a command that never
#     returns.
exec_always --no-startup-id sh -c 'pgrep -f "/usr/local/bin/i3-everforest-bar$" >/dev/null 2>&1 || /usr/local/bin/i3-everforest-bar &'
exec --no-startup-id i3-everforest-border
exec --no-startup-id i3-everforest-wifi-cache
exec --no-startup-id i3-everforest-idle
I3CONF
	install_user_file "${cfg}" 644 <"${tmp}"
	rm -f "${tmp}"
}

write_bar() {
	# The bar is a small C program: cairo + pango on a plain X11 dock window.
	# It reproduces the Waybar stylesheet that the GTK version used, at about a
	# twentieth of the memory (3 MB vs 62 MB) and without a Python runtime.
	#
	# The sources ship inside this installer and are compiled at install time,
	# so the target machine needs no source tree afterwards.
	local dir="${HOME_DIR}/.config/i3-everforest"
	local src="${ASSET_DIR}/bar-c"
	local build
	mkdir -p "${dir}"

	if [[ ! -d "${src}/src" ]]; then
		ui_warn "the bundled bar sources are missing"
		return 1
	fi

	if ! pkg-config --exists cairo pangocairo x11 2>/dev/null; then
		ui_warn "bar build needs libcairo2-dev, libpango1.0-dev and libx11-dev"
		return 1
	fi

	build="$(mktemp -d)"
	cp -r "${src}/src" "${build}/src"
	cp "${src}/Makefile" "${build}/Makefile"
	if ! ( cd "${build}" && make -s 2>/dev/null ); then
		ui_warn "the bar failed to build"
		rm -rf "${build}"
		return 1
	fi
	install -m 755 "${build}/i3-everforest-bar-c" /usr/local/bin/i3-everforest-bar
	rm -rf "${build}"
	register_file "/usr/local/bin/i3-everforest-bar"

	# The layout description mirrors the Waybar config key for key. Opacity is
	# handled specially: if a bar.json already exists, keep whatever the user
	# has selected there unless --opacity was passed explicitly. Reinstalling
	# used to silently reset the choice back to "solid".
	local opacity="${BAR_OPACITY}"
	if [[ -z "${OPT_OPACITY_GIVEN:-}" && -f "${dir}/bar.json" ]]; then
		local cur
		cur="$(sed -n 's/.*"opacity"[[:space:]]*:[[:space:]]*"\([a-z]*\)".*/\1/p' \
			"${dir}/bar.json" 2>/dev/null | head -1)"
		case "${cur}" in
		solid|soft|clear) opacity="${cur}" ;;
		esac
	fi
	[[ -n "${opacity}" ]] || opacity="solid"

	local tmp; tmp="$(mktemp)"
	if [[ -f "${ASSET_DIR}/bar/bar.json" ]]; then
		sed -e "s|\"opacity\": *\"[a-z]*\"|\"opacity\": \"${opacity}\"|" \
			"${ASSET_DIR}/bar/bar.json" >"${tmp}"
	fi
	install_user_file "${dir}/bar.json" 644 <"${tmp}"
	rm -f "${tmp}"
	ui_dim "bar opacity: ${opacity}"
}

write_bar_opacity() {
	# Change the bar's transparency preset at runtime.
	#
	#   i3-everforest-bar-opacity            cycle solid -> soft -> clear
	#   i3-everforest-bar-opacity clear      set one preset
	#
	# The preset lives in bar.json; the bar re-reads it on SIGHUP, so the change
	# applies immediately and survives the next login.
	local ctl="/usr/local/bin/i3-everforest-bar-opacity"
	cat >"${ctl}" <<'OPSH'
#!/bin/sh
# Change the bar transparency preset and reload the running bar.
export LC_ALL=C

cfg="${HOME}/.config/i3-everforest/bar.json"
[ -f "${cfg}" ] || { echo "no ${cfg}" >&2; exit 1; }

cur=$(sed -n 's/.*"opacity"[[:space:]]*:[[:space:]]*"\([a-z]*\)".*/\1/p' "${cfg}" | head -1)
[ -n "${cur}" ] || cur=solid

case "${1:-}" in
	solid|soft|clear) want="$1" ;;
	"")
		case "${cur}" in
		solid) want=soft ;;
		soft)  want=clear ;;
		*)     want=solid ;;
		esac
		;;
	*) echo "usage: $(basename "$0") [solid|soft|clear]" >&2; exit 2 ;;
esac

sed -i "s|\"opacity\"[[:space:]]*:[[:space:]]*\"[a-z]*\"|\"opacity\": \"${want}\"|" "${cfg}"

pid=$(ps -eo pid,args --no-headers 2>/dev/null |
	awk '$2 ~ /i3-everforest-bar$/ { print $1; exit }')
[ -n "${pid}" ] && kill -HUP "${pid}" 2>/dev/null

printf 'bar opacity: %s -> %s\n' "${cur}" "${want}"
OPSH
	chmod 755 "${ctl}"
	register_file "${ctl}"
	ui_ok "bar opacity switcher installed"
}

write_border_ctl() {
	# i3 reads `default_border` only at startup, so a window created after a
	# reload got no outline; and `hide_edge_borders` cannot tell a split pane
	# from a lone one. Decide per workspace instead: a single window fills the
	# workspace (no border), two or more are split (each keeps its border).
	local ctl="/usr/local/bin/i3-everforest-border"
	cat >"${ctl}" <<'BCTL'
#!/usr/bin/env python3
"""Keep window borders in step with the layout.

A lone window fills its workspace and should look edge-to-edge, so it gets no
outline; as soon as the workspace is split, every pane shows one.
"""
import i3ipc


def leaves(con):
    out = []

    def walk(c):
        if c.window is not None:
            out.append(c)
            return
        for n in c.nodes:
            walk(n)

    walk(con)
    return out


def apply(i3, _event=None):
    try:
        for ws in i3.get_tree().workspaces():
            panes = leaves(ws)
            want = "pixel" if len(panes) > 1 else "none"
            for c in panes:
                if c.name and "everforest-bar" in c.name:
                    continue
                if c.border != want:
                    c.command(f"border {want}")
    except Exception:
        pass


def main():
    i3 = i3ipc.Connection()
    apply(i3)
    for ev in ("window::new", "window::close", "window::move",
               "window::floating"):
        i3.on(ev, apply)
    i3.main()


if __name__ == "__main__":
    main()
BCTL
	chmod 755 "${ctl}"
	register_file "${ctl}"
	ui_ok "border controller installed"
}


# ---------------------------------------------------------------------
#  X11 session environment
# ---------------------------------------------------------------------
#  On Wayland, environment.d fed the session through systemd. An X session
#  started by a display manager or startx does not read it: it sources
#  ~/.xsessionrc (Debian's Xsession) and ~/.xprofile (startx), and tools like
#  im-config write ~/.xinputrc. Writing the same exports there is what makes
#  the theme, the cursor and the IME apply inside i3.
write_xsession_env() {
	local xsr="${HOME_DIR}/.xsessionrc"
	local marker_begin="# >>> i3-everforest >>>"
	local marker_end="# <<< i3-everforest <<<"

	if [[ ${OPT_DRY_RUN} -eq 1 ]]; then
		ui_dim "would write ${xsr}"
		return 0
	fi

	if grep -qF "${marker_begin}" "${xsr}" 2>/dev/null; then
		# The block already exists: make sure settings added since then are
		# present, without rewriting the whole file.
		if ! grep -q 'ST_ALPHA' "${xsr}" 2>/dev/null; then
			sed -i "/${marker_end}/i export ST_ALPHA=78" "${xsr}" 2>/dev/null
		fi
		ui_dim "unchanged: ${xsr}"
		return 0
	fi
	[[ -f "${xsr}" ]] && backup_path "${xsr}"

	cat >>"${xsr}" <<XSESS
${marker_begin}
# Session identity: every desktop-aware program (portals, Qt, GTK, OBS,
# browsers) keys off these.
export XDG_CURRENT_DESKTOP=i3
export XDG_SESSION_DESKTOP=i3
export XDG_SESSION_TYPE=x11
export DESKTOP_SESSION=i3
export XDG_SESSION_CLASS=user

# Toolkit hints for an X11 desktop.
export QT_QPA_PLATFORMTHEME=gtk3
export MOZ_ENABLE_WAYLAND=0
export _JAVA_AWT_WM_NONREPARENTING=1

# Use the polkit agent and the notification daemon this rice ships.
export GTK_THEME=${THEME_NAME}

# Keep the X clipboard alive after a client exits, so screenshots and the
# colour picker still paste.
export CLIPBOARD_PERSIST=1

# st reads its background alpha from here; keep the terminal translucent
# (60%) the way kitty's background_opacity 0.60 looks.
export ST_ALPHA=78

${marker_end}
XSESS
	register_file "${xsr}"
	chown_user "${xsr}" 2>/dev/null || true

	# ~/.Xresources: the GTK/cursor/Xft settings that X clients read at start.
	local xres="${HOME_DIR}/.Xresources"
	local rmark_begin="! >>> i3-everforest >>>"
	local rmark_end="! <<< i3-everforest <<<"
	if ! grep -qF "${rmark_begin}" "${xres}" 2>/dev/null; then
		[[ -f "${xres}" ]] && backup_path "${xres}"
		cat >>"${xres}" <<XRES
${rmark_begin}
Xft.dpi: 96
Xft.antialias: 1
Xft.hinting: 1
Xft.hintstyle: hintslight
Xft.rgba: rgb
Xcursor.theme: Adwaita
Xcursor.size: 24
${rmark_end}
XRES
		register_file "${xres}"
		chown_user "${xres}" 2>/dev/null || true
	fi
	ui_ok "X11 session environment written"
	return 0
}

user_dirs_create() {
	# xdg-user-dirs creates Desktop/Documents/Downloads/Music/Pictures/Videos
	# from the localized names in /etc/xdg/user-dirs.defaults. Without this the
	# bookmarks and the file manager sidebar point at directories that do not
	# exist yet.
	if command -v xdg-user-dirs-update >/dev/null 2>&1; then
		if [[ ${OPT_DRY_RUN} -eq 1 ]]; then
			ui_dim "would create the XDG user directories"
			return 0
		fi
		as_user xdg-user-dirs-update --force >/dev/null 2>&1 ||
			as_user xdg-user-dirs-update >/dev/null 2>&1 || true
	fi
	# Make sure the set we link to exists even when xdg-user-dirs is absent.
	local d
	for d in Desktop Documents Downloads Music Pictures Videos Public Templates; do
		[[ -d "${HOME_DIR}/${d}" ]] || mkdir -p "${HOME_DIR}/${d}" 2>/dev/null || true
		chown_user "${HOME_DIR}/${d}" 2>/dev/null || true
	done
	ui_ok "user directories ready"
	return 0
}

