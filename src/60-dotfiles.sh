# =====================================================================
#  Dotfiles: i3, the GTK bar, st, rofi, dunst, i3lock, btop
# ---------------------------------------------------------------------
#  Every file is written through install_user_file(), which backs up a
#  previous file and records it in the manifest for --uninstall.
#
#  This is an X11 desktop: the window manager is i3, the bar is a GTK3
#  program that draws the Waybar stylesheet, and the launcher is rofi. The
#  visual language (colours, geometry, keybindings)
#  is unchanged from the Wayland original.
# =====================================================================

install_user_file() {
	# install_user_file <abs-path> <mode>  (content on stdin)
	local path="$1" mode="${2:-644}"
	local tmp; tmp="$(mktemp)"
	cat >"${tmp}"          # read stdin exactly once
	if [[ -e "${path}" ]] && cmp -s "${tmp}" "${path}"; then
		rm -f "${tmp}"
		ui_dim "unchanged: ${path}"
		return 0
	fi
	mkdir -p "$(dirname "${path}")"
	if [[ -e "${path}" || -L "${path}" ]]; then
		backup_path "${path}"
	fi
	install -m "${mode}" "${tmp}" "${path}"
	rm -f "${tmp}"
	register_file "${path}"
	ui_ok "wrote ${path}"
}

